"""The server's public contract: every tool's name, schemas and annotations.

Used by the snapshot test (any change must be deliberate) and to generate
docs/tools.md, so the reference can't drift from the code.
"""

import json
from typing import Any

import anyio
from mcp import Client

from garmin_connect_personal_mcp.config import DataPaths
from garmin_connect_personal_mcp.server import build_server


def tools_contract(paths: DataPaths) -> list[dict[str, Any]]:
    """Every tool as the client sees it, sorted by name."""
    server = build_server(paths)

    async def main() -> list[dict[str, Any]]:
        async with Client(server) as client:
            tools = (await client.list_tools()).tools
        return [
            {
                "name": t.name,
                "title": t.title,
                "description": t.description,
                "annotations": t.annotations.model_dump(exclude_none=True) if t.annotations else {},
                "input_schema": t.input_schema,
                "output_schema": t.output_schema,
                "meta": t.meta or {},
            }
            for t in sorted(tools, key=lambda t: t.name)
        ]

    return anyio.run(main)


def contract_json(paths: DataPaths) -> str:
    return json.dumps(tools_contract(paths), indent=2, sort_keys=True) + "\n"


def _param_rows(schema: dict[str, Any]) -> list[str]:
    required = set(schema.get("required", []))
    rows = []
    for name, spec in schema.get("properties", {}).items():
        kind = spec.get("type", "")
        if "enum" in spec:
            values = spec["enum"]
            shown = ", ".join(f"`{v}`" for v in values[:6]) + (", …" if len(values) > 6 else "")
            kind = f"one of {shown}"
        default = "required" if name in required else f"default `{json.dumps(spec.get('default'))}`"
        rows.append(f"| `{name}` | {kind} | {default} | {spec.get('description', '')} |")
    return rows


def tools_markdown(paths: DataPaths) -> str:
    lines = [
        "# Tools reference",
        "",
        "<!-- Generated by `python scripts/gen_tools_doc.py`. Don't edit by hand. -->",
        "",
        "Every tool returns structured JSON (with a matching text copy). Units are in field "
        "names, and missing data is `null`, never zero. For UI-capable chart clients, the "
        "model receives summary JSON and a display acknowledgement instead; full plot arrays "
        "are delivered to the widget in result metadata. Non-UI chart clients keep the full "
        "structured/text data fallback.",
        "",
    ]
    for tool in tools_contract(paths):
        hints = tool["annotations"]
        flags = ["read-only" if hints.get("read_only_hint") else "writes the local archive"]
        flags.append("contacts Garmin" if hints.get("open_world_hint") else "local only")
        if tool["meta"].get("ui"):
            flags.append("shows an interactive chart in apps that support MCP Apps")
        lines += [f"## `{tool['name']}`", "", tool["description"], "", f"*{', '.join(flags)}*", ""]
        rows = _param_rows(tool["input_schema"])
        if rows:
            lines += [
                "| Parameter | Type | Default | Description |",
                "| --- | --- | --- | --- |",
                *rows,
                "",
            ]
        else:
            lines += ["No parameters.", ""]
    return "\n".join(lines)
